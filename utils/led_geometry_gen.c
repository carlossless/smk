
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int isqrt_i(int n)
{
    int r = 0;
    while ((r + 1) * (r + 1) <= n) {
        r++;
    }
    return r;
}

int main(int argc, char **argv)
{
    if (argc != 6) {
        fprintf(stderr, "usage: %s <header|source> <rows> <cols> <centre_x2> <centre_y2>\n", argv[0]);
        return 1;
    }

    const char *mode = argv[1];
    int         rows = atoi(argv[2]);
    int         cols = atoi(argv[3]);
    int         cx2  = atoi(argv[4]);
    int         cy2  = atoi(argv[5]);

    if (rows < 1 || rows > 64 || cols < 1 || cols > 64) {
        fprintf(stderr, "led_geometry_gen: rows/cols out of range (1..64)\n");
        return 1;
    }

    int dist[64][64];
    int maxd = 1;
    for (int r = 0; r < rows; r++) {
        for (int c = 0; c < cols; c++) {
            int dx     = 2 * c - cx2;
            int dy     = 2 * r - cy2;
            int d      = isqrt_i(dx * dx + dy * dy);
            dist[r][c] = d;
            if (d > maxd) {
                maxd = d;
            }
        }
    }

    if (strcmp(mode, "header") == 0) {
        printf("#pragma once\n");
        printf("// Generated by utils/led_geometry_gen.c - do not edit.\n");
        printf("// LED animation geometry sizes for a %dx%d matrix; centre (%d, %d) in half-cells.\n\n", rows, cols, cx2, cy2);
        printf("#define LED_GEOMETRY_ROWS %d\n", rows);
        printf("#define LED_GEOMETRY_COLS %d\n", cols);
        return 0;
    }

    if (strcmp(mode, "source") != 0) {
        fprintf(stderr, "%s: unknown mode '%s' (expected 'header' or 'source')\n", argv[0], mode);
        return 1;
    }

    printf("// Generated by utils/led_geometry_gen.c - do not edit.\n");
    printf("// LED animation geometry for a %dx%d matrix; centre (%d, %d) in half-cells.\n", rows, cols, cx2, cy2);
    printf("#include \"user_led.h\"\n\n");

    printf("static const __code uint8_t radial[%d][%d] = {\n", rows, cols);
    for (int r = 0; r < rows; r++) {
        printf("    {");
        for (int c = 0; c < cols; c++) {
            printf("%d%s", dist[r][c] * 255 / maxd, (c < cols - 1) ? ", " : "");
        }
        printf("},\n");
    }
    printf("};\n");

    printf("static const __code uint8_t axis_x[%d] = {", cols);
    for (int c = 0; c < cols; c++) {
        printf("%d%s", (c << 8) / cols, (c < cols - 1) ? ", " : "");
    }
    printf("};\n");

    printf("static const __code uint8_t axis_y[%d] = {", rows);
    for (int r = 0; r < rows; r++) {
        printf("%d%s", (r << 8) / rows, (r < rows - 1) ? ", " : "");
    }
    printf("};\n\n");

    printf("uint8_t user_led_radial(uint8_t row, uint8_t col) { return radial[row][col]; }\n");
    printf("uint8_t user_led_axis_x(uint8_t col) { return axis_x[col]; }\n");
    printf("uint8_t user_led_axis_y(uint8_t row) { return axis_y[row]; }\n");

    return 0;
}
